export function renderJson(report: DiffReport): string {
  return `${stableStringify(report)}\n`;
}

export function renderMarkdown(report: DiffReport): string {
  const { before, after, risk, policy, inventory, metadata } = report;
  const lines = [
    '# Depdiff audit report',
    '',
    `> **${escapeMarkdown(before.package.name)} ${escapeMarkdown(before.package.version)} → ${escapeMarkdown(after.package.version)}** · Risk **${risk.score}/100 (${risk.level})** · Policy **${policy.passed ? 'PASS' : 'FAIL'}**`,
    '',
    `Generated by Depdiff ${report.tool.version}. Package code executed: **no**.`,
    '',
    '## Change summary',
    '',
    '| Metric | Change |',
    '|---|---:|',
    `| Files | +${inventory.added.length} / −${inventory.removed.length} / ~${inventory.modified.length} |`,
    `| Unpacked size | ${byteSize(before.totalBytes)} → ${byteSize(after.totalBytes)} |`,
    `| Shipped dependencies added | ${metadata.dependencies.filter((change) => change.change === 'added' && change.scope !== 'development').length} |`,
    `| New findings | ${risk.newFindings} |`,
    `| Baseline findings | ${risk.baselineFindings} |`,
    '',
  ];
  if (!policy.passed) {
    lines.push('## Policy violations', '');
    for (const violation of policy.violations) lines.push(`- **${escapeMarkdown(violation.rule)}:** ${escapeMarkdown(violation.message)}`);
    lines.push('');
  }
  lines.push('## Findings', '');
  if (report.findings.length === 0) lines.push('No heuristic risk findings were detected.', '');
  for (const finding of report.findings) {
    lines.push(
      `### ${severityIcon(finding.severity)} ${escapeMarkdown(finding.title)}`,
      '',
      `**${finding.severity.toUpperCase()} · +${finding.score} · ${finding.category} · ${finding.status}**  `,
      `Rule: \`${finding.id}\` · Fingerprint: \`${finding.fingerprint}\``,
      '',
      escapeMarkdown(finding.description),
      '',
    );
    for (const evidence of finding.evidence) {
      lines.push(`- ${formatMarkdownEvidence(evidence)}`);
    }
    lines.push('', `**Review:** ${escapeMarkdown(finding.remediation)}`, '');
  }
  lines.push(
    '## Scope and limits',
    '',
    '- Static analysis only: Depdiff never runs package code or lifecycle scripts.',
    '- Findings are evidence-backed review signals, not a malware verdict.',
    '- Dynamic destinations and behavior assembled at runtime can evade static analysis.',
    '',
  );
  return `${lines.join('\n')}\n`;
}

export function renderSarif(report: DiffReport, options: ReportRenderOptions = {}): string {
  const rules = [...new Map(report.findings.map((finding) => [finding.id, finding])).values()].map((finding) => ({
    id: finding.id,
    name: sarifName(finding.id),
    shortDescription: { text: finding.title },
    fullDescription: { text: finding.description },
    help: { text: finding.remediation },
    properties: { category: finding.category, tags: finding.tags, defaultSeverity: finding.severity },
  }));
  const results = report.findings.map((finding) => {
    const firstEvidence = finding.evidence[0];
    const evidencePath = firstEvidence?.file
      ? resolveWorkspaceEvidencePath(report, firstEvidence.file, options.workspace)
      : undefined;
    return {
      ruleId: finding.id,
      level: sarifLevel(finding.severity),
      message: { text: `${finding.title}: ${finding.description}` },
      ...(evidencePath ? {
        locations: [{ physicalLocation: {
          artifactLocation: { uri: evidencePath.split('/').map((segment) => encodeURIComponent(segment)).join('/') },
          ...(firstEvidence?.line ? { region: { startLine: firstEvidence.line } } : {}),
        } }],
      } : {}),
      partialFingerprints: { depdiffFingerprint: finding.fingerprint },
      baselineState: finding.status === 'baseline' ? 'unchanged' : 'new',
      properties: {
        score: finding.score,
        severity: finding.severity,
        category: finding.category,
        evidence: finding.evidence,
      },
    };
  });
  const sarif = {
    version: '2.1.0',
    $schema: 'https://json.schemastore.org/sarif-2.1.0.json',
    runs: [{
      tool: { driver: {
        name: 'Depdiff',
        informationUri: 'https://github.com/yewud/depdiff',
        semanticVersion: report.tool.version,
        rules,
      } },
      invocations: [{ executionSuccessful: true, exitCode: report.policy.passed ? 0 : 1 }],
      results,
    }],
  };
  return `${stableStringify(sarif)}\n`;
}

