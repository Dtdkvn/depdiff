function renderFindingCard(finding: Finding): string {
  const evidence = finding.evidence.length === 0 ? '<li>No location-specific evidence.</li>' : finding.evidence.map((item) => `<li>${item.file ? `<b>${escapeHtml(item.file)}${item.line ? `:${item.line}` : ''}</b> · ` : ''}${escapeHtml(item.message)}${item.snippet ? `<code>${escapeHtml(item.snippet)}</code>` : ''}</li>`).join('');
  return `<article class="finding" data-severity="${finding.severity}" data-search="${escapeHtml(finding.id)}"><div class="finding-top"><span class="severity">${finding.severity.toUpperCase()}</span><div class="finding-copy"><h3>${escapeHtml(finding.title)}${finding.status === 'baseline' ? '<span class="baseline-badge">BASELINE</span>' : ''}</h3><p>${escapeHtml(finding.description)}</p><div class="rule">${escapeHtml(finding.id)} · ${escapeHtml(finding.fingerprint)}</div></div><span class="score">+${finding.score}</span></div><details><summary>${finding.evidence.length} evidence item${finding.evidence.length === 1 ? '' : 's'}</summary><ul class="evidence">${evidence}</ul><p class="remediation"><b>Review guidance:</b> ${escapeHtml(finding.remediation)}</p></details></article>`;
}

function renderPaths(...groups: Array<Array<[string, string]>>): string {
  const entries = groups.flat();
  if (entries.length === 0) return '<li>No changes in this group.</li>';
  return entries.slice(0, 500).map(([symbol, file]) => `<li><span class="${symbol === '+' ? 'plus' : symbol === '−' ? 'minus' : 'tilde'}">${symbol}</span> ${escapeHtml(file)}</li>`).join('') + (entries.length > 500 ? `<li>… ${entries.length - 500} more paths in JSON report</li>` : '');
}

function safeScriptJson(value: unknown): string {
  return JSON.stringify(value).replace(/[<>&\u2028\u2029]/g, (character) => `\\u${character.charCodeAt(0).toString(16).padStart(4, '0')}`);
}

function escapeHtml(value: string): string {
  return value.replace(/[&<>"']/g, (character) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[character] ?? character);
}

function escapeMarkdown(value: string): string {
  return sanitizeSingleLine(value).replace(/([\\`*_[\]<>|#])/g, '\\$1');
}

function formatMarkdownEvidence(evidence: Evidence): string {
  const location = evidence.file ? `\`${escapeMarkdown(evidence.file)}${evidence.line ? `:${evidence.line}` : ''}\` — ` : '';
  const snippet = evidence.snippet ? ` — \`${escapeMarkdown(evidence.snippet)}\`` : '';
  return `${location}${escapeMarkdown(evidence.message)}${snippet}`;
}

function severityIcon(severity: Severity): string {
  return ({ critical: '🔴', high: '🟠', medium: '🟡', low: '🔵', info: '⚪' } satisfies Record<Severity, string>)[severity];
}

function sarifLevel(severity: Severity): 'error' | 'warning' | 'note' | 'none' {
  if (severity === 'critical' || severity === 'high') return 'error';
  if (severity === 'medium') return 'warning';
  if (severity === 'low' || severity === 'info') return 'note';
  return 'none';
}

function sarifName(id: string): string {
  return id.split(/[.-]/).map((part) => `${part.slice(0, 1).toUpperCase()}${part.slice(1)}`).join('');
}

export function resolveWorkspaceEvidencePath(report: DiffReport, evidenceFile: string, workspace?: string): string | undefined {
  if (!workspace || report.after.source.kind !== 'directory') return undefined;
  const sourceRoot = path.resolve(report.after.source.resolved);
  const candidate = path.resolve(sourceRoot, evidenceFile);
  if (!isWithin(sourceRoot, candidate)) return undefined;
  const workspaceRoot = path.resolve(workspace);
  if (!isWithin(workspaceRoot, candidate)) return undefined;
  const relative = path.relative(workspaceRoot, candidate).split(path.sep).join('/');
  return relative && !relative.startsWith('../') ? relative : undefined;
}

function isWithin(root: string, candidate: string): boolean {
  const relative = path.relative(root, candidate);
  return relative === '' || (!relative.startsWith('..') && !path.isAbsolute(relative));
}

function sanitizeSingleLine(value: string): string {
  return value
    .replace(/\r\n?|\n/g, ' ')
    .replace(CONTROL_CHARACTER_PATTERN, ' ')
    .replace(/\s{2,}/g, ' ')
    .trim();
}

// Intentional report-control sanitizer.
// eslint-disable-next-line no-control-regex
const CONTROL_CHARACTER_PATTERN = new RegExp('[\\u0000-\\u0008\\u000b\\u000c\\u000e-\\u001f\\u007f-\\u009f]', 'g');

function riskColor(level: DiffReport['risk']['level']): string {
  return ({ critical: '#ff5f72', high: '#ff8a5b', medium: '#f5c451', low: '#6bd6e8', none: '#3ddc97' })[level];
}

function signedBytes(value: number): string {
  return `${value >= 0 ? '+' : '−'}${byteSize(Math.abs(value))}`;
}
